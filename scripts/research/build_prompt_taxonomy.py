#!/usr/bin/env python3
"""Emit the prompt taxonomy as a prompts file plus an auditable coverage report.

The prompts file feeds ``encode_kimodo_prompts.py`` and ``generate_kimodo_motions.py``;
the JSON keeps each prompt's axis values so acceptance and behaviour metrics can later be
reported per axis rather than as one pooled number.

Usage::

    python scripts/research/build_prompt_taxonomy.py --out /data/.../taxonomy
"""

from __future__ import annotations

import argparse
from dataclasses import asdict
import json
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from gear_sonic.dataset_generation.prompt_taxonomy import (  # noqa: E402
    BODY_MODES,
    SPEED_STYLES,
    TURN_STYLES,
    build_taxonomy,
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True, help="output directory")
    parser.add_argument("--body-modes", nargs="*", default=None)
    parser.add_argument("--speeds", nargs="*", default=None)
    parser.add_argument("--turns", nargs="*", default=None)
    parser.add_argument("--list-axes", action="store_true", help="print axis values and exit")
    args = parser.parse_args()

    if args.list_axes:
        print("body modes:", ", ".join(BODY_MODES))
        print("speeds:    ", ", ".join(SPEED_STYLES))
        print("turns:     ", ", ".join(TURN_STYLES))
        return 0

    taxonomy = build_taxonomy(
        body_modes=args.body_modes or None,
        speeds=args.speeds or None,
        turns=args.turns or None,
    )
    args.out.mkdir(parents=True, exist_ok=True)

    prompts_path = args.out / "prompts.txt"
    header = [
        "# Generated by scripts/research/build_prompt_taxonomy.py -- do not hand-edit.",
        "# Axis values for each prompt are in taxonomy.json alongside this file.",
    ]
    prompts_path.write_text("\n".join(header + taxonomy.prompts) + "\n", encoding="utf-8")

    report = {
        "prompt_count": len(taxonomy.specs),
        "non_walk_count": sum(spec.is_non_walk for spec in taxonomy.specs),
        "coverage": taxonomy.counts,
        "specs": [asdict(spec) for spec in taxonomy.specs],
    }
    (args.out / "taxonomy.json").write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    print(f"{len(taxonomy.specs)} prompts ({report['non_walk_count']} non-walk) -> {prompts_path}")
    for axis, counts in taxonomy.counts.items():
        rendered = ", ".join(f"{k}={v}" for k, v in sorted(counts.items()))
        print(f"  {axis:10s} {rendered}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
