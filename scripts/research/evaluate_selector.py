#!/usr/bin/env python
"""Validate the minimal-adaptation selector's harness on synthetic families.

This proves the *controls*, not the method. Synthetic ground truth is generated by the rule the
privileged model should be able to learn -- a candidate survives when every geometric margin is
positive -- so the informative outputs are the control rows, which must collapse:

    no-scene       must fall to roughly the majority-class rate; the model cannot see geometry
    scene-shuffle  must fall likewise; it is scored against the real scene's ground truth
    candidate-order must NOT move; the lexicographic rule is order-invariant by construction

If a control fails to collapse, any accuracy on real families is suspect for the same reason.
Real families replace `synthetic_families` once enough are physics-verified; nothing here is
evidence about SONIC or about scenes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from gear_sonic.dataset_generation.compatibility_selector import (  # noqa: E402
    Candidate,
    CompatibilityModel,
    Family,
    evaluate,
    holdout,
    training_matrix,
)

#: The three-candidate bank the design plan specifies: nominal, local crouch, local arm tuck.
#: Costs are ordinal placeholders -- the lexicographic rule needs only the ordering, and the
#: weights are explicitly not frozen yet.
BANK = (
    ("nominal", 0.0, {"peak_height_m": 1.305, "half_width_left_m": 0.290,
                      "half_width_right_m": 0.290, "foot_clearance_m": 0.120}),
    ("crouch", 1.0, {"peak_height_m": 1.207, "half_width_left_m": 0.292,
                     "half_width_right_m": 0.292, "foot_clearance_m": 0.118}),
    ("tuck", 1.0, {"peak_height_m": 1.303, "half_width_left_m": 0.256,
                   "half_width_right_m": 0.268, "foot_clearance_m": 0.120}),
)


def synthetic_families(count: int, *, seed: int, nominals: int = 6) -> list[Family]:
    """Families whose scenes span the overhead and lateral regimes near the decision boundary.

    Scenes are drawn tight on purpose. Sampling generously would make every candidate succeed and
    the selector would score well by always answering "nominal".
    """
    rng = np.random.default_rng(seed)
    out: list[Family] = []
    for i in range(count):
        nominal_id = f"n{i % nominals:02d}"
        regime = "overhead" if i % 2 == 0 else "lateral"
        jitter = rng.normal(0.0, 0.006, 4)
        if regime == "overhead":
            scene = {"overhead_clearance_m": float(rng.uniform(1.19, 1.34)),
                     "left_gap_m": 0.45, "right_gap_m": 0.45, "floor_height_m": 0.0}
        else:
            scene = {"overhead_clearance_m": 1.60,
                     "left_gap_m": float(rng.uniform(0.25, 0.30)),
                     "right_gap_m": 0.45, "floor_height_m": 0.0}
        cands = []
        for name, cost, base in BANK:
            prof = {k: float(v + j) for (k, v), j in zip(base.items(), jitter)}
            succeeds = (
                prof["peak_height_m"] < scene["overhead_clearance_m"]
                and prof["half_width_left_m"] < scene["left_gap_m"]
                and prof["half_width_right_m"] < scene["right_gap_m"]
                and prof["foot_clearance_m"] > scene["floor_height_m"]
            )
            cands.append(Candidate(f"{nominal_id}_{name}", nominal_id, prof, cost, succeeds))
        out.append(Family(f"syn{i:03d}", scene, tuple(cands)))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--families", type=int, default=240)
    ap.add_argument("--seed", type=int, default=20260818)
    ap.add_argument("--json", type=Path)
    args = ap.parse_args()

    fams = synthetic_families(args.families, seed=args.seed)
    scorable = [f for f in fams if f.optimum() is not None]
    needs = sum(1 for f in scorable if f.optimum().cost > 0.0)
    print(f"synthetic families: {len(fams)}  scorable: {len(scorable)}  "
          f"needing adaptation: {needs} ({needs / max(1, len(scorable)):.0%})")
    print("  a selector that always answers 'nominal' scores "
          f"{1 - needs / max(1, len(scorable)):.0%} -- that is the bar to beat\n")

    report: dict = {"seed": args.seed, "families": len(fams), "splits": {}}
    for axis in ("family", "nominal"):
        rows = []
        for control in ("none", "no-scene", "scene-shuffle", "candidate-order"):
            acc, fs, un, rg, ab, n = [], [], [], [], [], 0
            for fold in range(4):
                train, test = holdout(fams, by=axis, fold=fold)
                if not train or not test:
                    continue
                x, y = training_matrix(train)
                model = CompatibilityModel(seed=args.seed + fold).fit(x, y)
                m = evaluate(model, test, control=control, seed=args.seed + fold)
                if not m.families:
                    continue
                acc.append(m.choice_accuracy); fs.append(m.false_safe_rate)
                un.append(m.unnecessary_adaptation_rate); rg.append(m.cost_regret)
                ab.append(m.abstention_rate); n += m.families
            rows.append({"control": control, "folds": len(acc), "families": n,
                         "choice_accuracy": round(float(np.mean(acc)), 4),
                         "false_safe_rate": round(float(np.mean(fs)), 4),
                         "unnecessary_adaptation_rate": round(float(np.mean(un)), 4),
                         "cost_regret": round(float(np.mean(rg)), 4),
                         "abstention_rate": round(float(np.mean(ab)), 4)})
        report["splits"][axis] = rows
        print(f"holdout by {axis}:")
        print(f"  {'control':>16s}{'choice':>9s}{'false-safe':>12s}{'unnec.':>9s}"
              f"{'regret':>9s}{'abstain':>9s}")
        for r in rows:
            print(f"  {r['control']:>16s}{r['choice_accuracy']:9.3f}{r['false_safe_rate']:12.3f}"
                  f"{r['unnecessary_adaptation_rate']:9.3f}{r['cost_regret']:9.3f}"
                  f"{r['abstention_rate']:9.3f}")
        print()

    if args.json:
        args.json.write_text(json.dumps(report, indent=2) + "\n")
        print(f"wrote {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
